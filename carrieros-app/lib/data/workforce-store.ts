export function listByTenant<T extends { tenantId: string }>(
  items: T[],
  tenantId = DEMO_TENANT_ID,
): T[] {
  return items.filter((item) => item.tenantId === tenantId);
}

export function getCompanyById(id: string) {
  return companyStore.find((c) => c.id === id);
}

export function getCandidateById(id: string) {
  return candidateStore.find((c) => c.id === id);
}

export function getJobById(id: string) {
  return jobStore.find((j) => j.id === id);
}

export function getApplicationById(id: string) {
  return applicationStore.find((a) => a.id === id);
}

export function updateApplicationStatus(id: string, status: Application["status"]) {
  const app = getApplicationById(id);
  if (!app) return null;
  app.status = status;
  app.updatedAt = new Date().toISOString();
  auditLogStore.unshift({
    id: `al-${Date.now()}`,
    at: app.updatedAt,
    actor: "You",
    action: `Moved application to ${status}`,
    entityType: "application",
    entityId: id,
  });
  return app;
}

export function createJob(input: Omit<JobPosting, "tenantId" | "id" | "postedAt" | "applicantsCount" | "savedCount">) {
  const job: JobPosting = {
    ...input,
    tenantId: T,
    id: `job-${Date.now()}`,
    postedAt: new Date().toISOString(),
    applicantsCount: 0,
    savedCount: 0,
  };
  jobStore.unshift(job);
  const company = getCompanyById(job.companyId);
  if (company) company.openPositions += 1;
  auditLogStore.unshift({
    id: `al-${Date.now()}`,
    at: job.postedAt,
    actor: "You",
    action: `Published job “${job.title}”`,
    entityType: "job",
    entityId: job.id,
  });
  return job;
}

export function updateJob(id: string, patch: Partial<JobPosting>) {
  const job = getJobById(id);
  if (!job) return null;
  Object.assign(job, patch);
  return job;
}

export function applyToJob(jobId: string, candidateId: string, coverNote?: string) {
  const job = getJobById(jobId);
  const candidate = getCandidateById(candidateId);
  if (!job || !candidate) return null;
  const existing = applicationStore.find(
    (a) => a.jobId === jobId && a.candidateId === candidateId,
  );
  if (existing) return existing;
  const app: Application = {
    tenantId: T,
    id: `app-${Date.now()}`,
    jobId,
    candidateId,
    companyId: job.companyId,
    status: "applied",
    appliedAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    matchScore: candidate.matchScore,
    coverNote,
    notes: [],
    source: "One-click apply",
  };
  applicationStore.unshift(app);
  job.applicantsCount += 1;
  return app;
}

export function scheduleInterview(input: Omit<Interview, "tenantId" | "id" | "status">) {
  const interview: Interview = {
    ...input,
    tenantId: T,
    id: `int-${Date.now()}`,
    status: "scheduled",
  };
  interviewStore.unshift(interview);
  const app = getApplicationById(input.applicationId);
  if (app && app.status === "applied") {
    updateApplicationStatus(app.id, "interview");
  } else if (app && app.status === "screening") {
    updateApplicationStatus(app.id, "interview");
  }
  auditLogStore.unshift({
    id: `al-${Date.now()}`,
    at: new Date().toISOString(),
    actor: "You",
    action: "Scheduled interview",
    entityType: "interview",
    entityId: interview.id,
  });
  return interview;
}

export function toggleOnboardingItem(checklistId: string, itemId: string) {
  const list = onboardingStore.find((o) => o.id === checklistId);
  if (!list) return null;
  const item = list.items.find((i) => i.id === itemId);
  if (!item) return null;
  item.completed = !item.completed;
  const done = list.items.filter((i) => i.completed).length;
  list.progress = Math.round((done / list.items.length) * 100);
  list.status = list.progress === 100 ? "complete" : "in_progress";
  return list;
}

export function sendThreadMessage(threadId: string, body: string, senderName = "You") {
  const thread = messageThreadStore.find((t) => t.id === threadId);
  if (!thread) return null;
  const msg: Message = {
    id: `m-${Date.now()}`,
    threadId,
    sender: "employer",
    senderName,
    body,
    sentAt: new Date().toISOString(),
  };
  messageStore.push(msg);
  thread.lastMessageAt = msg.sentAt;
  thread.preview = body;
  thread.unread = 0;
  return msg;
}

