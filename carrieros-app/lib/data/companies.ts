export function listCompaniesByTenant(tenantId: string): DirectoryCompany[] {
  return companies.filter((company) => company.tenantId === tenantId);
}

export function getCompanyById(id: string): DirectoryCompany | undefined {
  return companies.find((company) => company.id === id);
}

export function getCompanyContact(
  company: DirectoryCompany,
  role: DirectoryCompany["contacts"][number]["role"],
) {
  return company.contacts.find((contact) => contact.role === role);
}

export function getCompanyByLinkedBrokerId(
  brokerId: string,
): DirectoryCompany | undefined {
  return companies.find((company) => company.linkedBrokerId === brokerId);
}

export function getCompanyByLinkedCustomerId(
  customerId: string,
): DirectoryCompany | undefined {
  return companies.find((company) => company.linkedCustomerId === customerId);
}

export function formatCompanyAddress(
  address?: DirectoryCompany["address"],
): string {
  if (!address) {
    return "";
  }

  const cityState = [address.city, address.state].filter(Boolean).join(", ");
  return [address.street, cityState, address.zip].filter(Boolean).join(" · ");
}

export function formatCompanyCityState(
  address?: DirectoryCompany["address"],
): string {
  if (!address) {
    return "";
  }

  return [address.city, address.state].filter(Boolean).join(", ");
}
