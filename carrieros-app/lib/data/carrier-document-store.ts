function version(
  id: string,
  versionNumber: number,
  filename: string,
  sizeBytes: number,
  uploadedAt: string,
  uploadedBy: string,
  note?: string,
): DocumentVersion {
  return { id, version: versionNumber, filename, sizeBytes, uploadedAt, uploadedBy, note };
}

function audit(
  id: string,
  action: DocumentAuditEntry["action"],
  actorName: string,
  actorRole: string,
  occurredAt: string,
  detail?: string,
): DocumentAuditEntry {
  return { id, action, actorName, actorRole, occurredAt, detail };
}

function timeline(
  id: string,
  documentId: string,
  type: DocumentTimelineEvent["type"],
  label: string,
  occurredAt: string,
  actorName?: string,
): DocumentTimelineEvent {
  return { id, documentId, type, label, occurredAt, actorName };
}

