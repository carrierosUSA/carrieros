export function listCarrierDocuments(tenantId: string): CarrierDocument[] {
  return carrierDocumentStore.filter((doc) => doc.tenantId === tenantId);
}

export function getCarrierDocumentById(
  tenantId: string,
  id: string,
): CarrierDocument | undefined {
  return carrierDocumentStore.find((doc) => doc.tenantId === tenantId && doc.id === id);
}

export function cloneCarrierDocuments(tenantId: string): CarrierDocument[] {
  return structuredClone(listCarrierDocuments(tenantId));
}
